package ru.rznnike.demokmp.data.storage

import androidx.room.Room
import androidx.room.useReaderConnection
import androidx.sqlite.driver.bundled.BundledSQLiteDriver
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.test.runTest
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import ru.rznnike.demokmp.data.storage.dao.DBExampleDataDao
import ru.rznnike.demokmp.data.storage.dao.LogMessageDao
import ru.rznnike.demokmp.data.storage.dao.LogNetworkMessageDao
import ru.rznnike.demokmp.data.storage.entity.DBExampleDataEntity
import java.io.File
import java.nio.file.Files
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertIs

private const val DB_CLASS_NAME = "ru.rznnike.demokmp.data.storage.MainDB"
private const val PINNED_SCHEMA_VERSION = 1
private const val MASTER_TABLE_ID = 42

/**
 * Guards the persistence contract of [MainDB] at the schema level, not the query level - the DAO
 * contracts are pinned separately in `data.storage.dao`.
 *
 * The identity hash is generated by Room from the entity declarations and written into
 * `room_master_table` when the database is created. Comparing it with the hash recorded in the
 * exported schema JSON is what detects a silent schema drift: Room overwrites the JSON on every
 * build, so the file itself cannot be trusted as a "before" snapshot - only the hash the running
 * database actually reports can.
 *
 * ## Migration policy (decided 2026-10-23)
 * Both platform modules configure `fallbackToDestructiveMigration(dropAllTables = true)`
 * (`DatabaseModule.desktop.kt:16`, `DatabaseModule.android.kt:17`). This is intentional for a demo
 * project: a version bump discards **every** table, including `DBExampleDataEntity` user data, and
 * always starts from an empty database. The policy is not a runtime safety net for schema mistakes:
 * a changed schema at the *same* version fails the identity check with an `IllegalStateException`
 * instead of being wiped.
 *
 * Consequence: bumping [MainDB]'s version is a data-destroying change. [PINNED_SCHEMA_VERSION]
 * makes that bump fail the build until a real migration test (`androidx.room:room-testing`,
 * `MigrationTestHelper` - it has a JVM variant) is added and the destructive fallback is revisited.
 *
 * Lives in `desktopTest` for the same reason as the other Room tests: `sqlite-bundled` native
 * libraries cannot load inside Android unit tests on the host JVM.
 */
class MainDBTest {
    private val databases = mutableListOf<MainDB>()
    private val tempDirs = mutableListOf<File>()

    @AfterTest
    fun tearDown() {
        databases.forEach { it.close() }
        databases.clear()
        tempDirs.forEach { it.deleteRecursively() }
        tempDirs.clear()
    }

    private fun createInMemoryDatabase(): MainDB = Room
        .inMemoryDatabaseBuilder<MainDB>()
        .setDriver(BundledSQLiteDriver())
        .setQueryCoroutineContext(Dispatchers.IO)
        .build()
        .also { databases += it }

    /** Mirrors the production builder in `DatabaseModule.desktop.kt`. */
    private fun createFileDatabase(file: File): MainDB = Room
        .databaseBuilder<MainDB>(name = file.absolutePath)
        .fallbackToDestructiveMigration(dropAllTables = true)
        .setDriver(BundledSQLiteDriver())
        .setQueryCoroutineContext(Dispatchers.IO)
        .build()

    private fun createTempDatabaseFile(): File {
        val dir = Files.createTempDirectory("demokmp-maindb").toFile()
        tempDirs += dir
        return File(dir, "main.db")
    }

    private suspend fun MainDB.readIdentityHash(): String? =
        useReaderConnection { connection ->
            connection.usePrepared(
                "SELECT identity_hash FROM ${Room.MASTER_TABLE_NAME} WHERE id = $MASTER_TABLE_ID LIMIT 1"
            ) { statement ->
                if (statement.step()) statement.getText(0) else null
            }
        }

    private fun exportedDatabase(): JsonObject {
        val relativePath = "schemas/$DB_CLASS_NAME/$PINNED_SCHEMA_VERSION.json"
        val file = generateSequence(File(System.getProperty("user.dir")).absoluteFile) { it.parentFile }
            .map { File(it, relativePath) }
            .firstOrNull { it.isFile }
            ?: error(
                "Exported schema '$relativePath' not found in any parent of " +
                    "'${System.getProperty("user.dir")}'. Is exportSchema/room.schemaDirectory set?"
            )
        return Json
            .parseToJsonElement(file.readText())
            .jsonObject
            .getValue("database")
            .jsonObject
    }

    @Test
    fun `generated identity hash matches the exported schema`() = runTest {
        // Arrange
        val database = createInMemoryDatabase()
        val exportedHash = exportedDatabase().getValue("identityHash").jsonPrimitive.content

        // Act
        val generatedHash = database.readIdentityHash()

        // Assert
        assertEquals(
            exportedHash,
            generatedHash,
            "The exported schema JSON no longer describes the generated database. " +
                "Check the entity declarations against schemas/$DB_CLASS_NAME/$PINNED_SCHEMA_VERSION.json."
        )
    }

    @Test
    fun `MainDB exposes all three DAOs`() {
        // Arrange
        val database = createInMemoryDatabase()

        // Act
        val daos = listOf(
            database.getLogMessageDao(),
            database.getLogNetworkMessageDao(),
            database.getDBExampleDataDao()
        )

        // Assert
        assertIs<LogMessageDao>(daos[0])
        assertIs<LogNetworkMessageDao>(daos[1])
        assertIs<DBExampleDataDao>(daos[2])
    }

    @Test
    fun `file-backed database keeps data across a reopen`() = runTest {
        // Arrange
        val file = createTempDatabaseFile()
        val data = DBExampleDataEntity(id = 1, name = "persisted")
        createFileDatabase(file).apply {
            getDBExampleDataDao().add(data)
            close()
        }

        // Act: reopening runs Room's identity check against the stored room_master_table row
        val reopened = createFileDatabase(file).also { databases += it }
        val result = reopened.getDBExampleDataDao().get(id = data.id)

        // Assert
        assertEquals(data, result)
    }

    @Test
    fun `exported schema declares all three tables`() {
        // Act
        val tables = exportedDatabase()
            .getValue("entities")
            .jsonArray
            .map { it.jsonObject.getValue("tableName").jsonPrimitive.content }
            .sorted()

        // Assert
        assertEquals(
            listOf("DBExampleDataEntity", "LogMessageEntity", "LogNetworkMessageEntity"),
            tables
        )
    }

    @Test
    fun `exported schema version is still 1`() {
        // Act
        val version = exportedDatabase().getValue("version").jsonPrimitive.int

        // Assert
        assertEquals(
            PINNED_SCHEMA_VERSION,
            version,
            "MainDB version changed. A version bump with " +
                "fallbackToDestructiveMigration(dropAllTables = true) wipes every table, " +
                "including DBExampleDataEntity user data. Add a MigrationTestHelper-based " +
                "migration test before bumping the version, then update this pin."
        )
    }
}
